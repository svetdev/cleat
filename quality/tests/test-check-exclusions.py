#!/usr/bin/env python3
"""test-check-exclusions — assert the ratchet on files marked as generated.

Over a throwaway tree with one real generator's output baselined: the gate
passes; a hand-written file given a generator's header fails, naming it and
what fixes it; prose that only mentions the words is not a header; a file
whose header is removed is a stale entry, a NOTE that --tighten drops and
--strict refuses; a symlink and a file under a skipped directory are not read.
Writes nothing outside a temporary directory.

  python3 quality/tests/test-check-exclusions.py
"""
import json, os, shutil, sys, tempfile
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from harness import Suite, write, run
SCRIPT = os.path.join(os.path.dirname(HERE), "bin", "check-exclusions.py")
suite = Suite("test-check-exclusions"); check = suite.check
HEADER = "// Code generated by protoc-gen-go. DO NOT " + "EDIT.\n"   # split, so this suite is not a generated file itself

tmp = tempfile.mkdtemp(prefix="exclusions-")
try:
    config = os.path.join(tmp, "quality.json")
    write(config, json.dumps({"exclusions": {"skip_dirs": ["vendored"], "baseline": "exclusions-baseline.json"}}))
    write(os.path.join(tmp, "api", "service.pb.go"), HEADER + "package api\n" * 40)
    write(os.path.join(tmp, "api", "handler.go"), "package api\n" * 10)
    write(os.path.join(tmp, "vendored", "lib.go"), HEADER + "package lib\n")
    code, out = run(SCRIPT, "--config", config, "--write-baseline")
    check("a person accepts the generator's output once", code == 0 and "1 generated file(s) accepted" in out, out)
    code, out = run(SCRIPT, "--config", config)
    check("with nothing new, the gate passes", code == 0 and "1 generated file(s), all in the baseline" in out, out)

    write(os.path.join(tmp, "api", "handler.go"), "// @generated" + " by hand, to hide it\n" + "package api\n" * 10)
    code, out = run(SCRIPT, "--config", config)
    check("a hand-written file given a generator's header fails, naming it", code == 1 and "api/handler.go" in out and "1 new generated file(s)" in out, out)
    check("and says what fixes it, never how to accept it", "remove the header" in out and "--write-baseline" not in out, out)

    write(os.path.join(tmp, "api", "handler.go"), "// a note: tools mark their output DO NOT" + " EDIT; this file is not one\npackage api\n")
    write(os.path.join(tmp, "api", "doc.go"), "/*\nPackage api. Its .pb.go files say @gener" + "ated in prose here.\n*/\npackage api\n")
    code, out = run(SCRIPT, "--config", config)
    check("prose that mentions the words is not a header", code == 0, out)
    os.symlink(os.path.join(tmp, "api", "service.pb.go"), os.path.join(tmp, "api", "link.pb.go"))
    code, out = run(SCRIPT, "--config", config)
    check("a symlink is the file it points at, read once, and a skipped directory is not read", code == 0 and "1 generated file(s)" in out, out)

    write(os.path.join(tmp, "api", "service.pb.go"), "package api\n" * 40)
    code, out = run(SCRIPT, "--config", config)
    check("a file no longer generated is a stale entry, a NOTE", code == 0 and "matched nothing this run" in out and "--tighten" in out, out)
    code, out = run(SCRIPT, "--config", config, "--strict")
    check("which --strict refuses", code == 1, out)
    code, out = run(SCRIPT, "--config", config, "--tighten")
    entries = json.load(open(os.path.join(tmp, "exclusions-baseline.json")))["entries"]
    check("and --tighten drops, never adding one", code == 0 and entries == [], str(entries))

    write(config, json.dumps({"project": "x"}))
    code, out = run(SCRIPT, "--config", config)
    check("a config without the section is refused naming it", code == 2 and '"exclusions"' in out, out)
finally:
    shutil.rmtree(tmp, ignore_errors=True)

suite.finish()
